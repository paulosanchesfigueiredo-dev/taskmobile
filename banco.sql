CREATE TABLE tarefas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo TEXT NOT NULL,
  concluida BOOLEAN DEFAULT FALSE,
  criada_em TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE tarefas ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Leitura de tarefas" ON tarefas FOR SELECT TO anon USING (true);
CREATE POLICY "Cadastro de tarefas" ON tarefas FOR INSERT TO anon WITH CHECK (true);
CREATE POLICY "Atualizacao de tarefas" ON tarefas FOR UPDATE TO anon USING (true) WITH CHECK (true);
CREATE POLICY "Exclusao de tarefas" ON tarefas FOR DELETE TO anon USING (true);

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE tarefas TO anon;
GRANT USAGE, SELECT ON SEQUENCE tarefas_id_seq TO anon;
